#!/usr/bin/env node
// Rebuilds skills/ascii-art/scripts/width.mjs from the Unicode data file.
// Run it when a new Unicode version ships:
//
//   curl -sSfLO https://www.unicode.org/Public/UCD/latest/ucd/EastAsianWidth.txt
//   node reviews/ascii-art/gen-width-tables.mjs EastAsianWidth.txt > skills/ascii-art/scripts/width.mjs

import { readFileSync } from 'node:fs'

const file = process.argv[2]
if (!file) {
  console.error('usage: node gen-width-tables.mjs EastAsianWidth.txt')
  process.exit(2)
}
const text = readFileSync(file, 'utf8')
const version = text.match(/EastAsianWidth-([\d.]+)\.txt/)?.[1] ?? 'unknown'

const wide = []
const ambiguous = []
for (const line of text.split('\n')) {
  const m = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/)
  if (!m) continue
  const range = [parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16)]
  if (m[3] === 'W' || m[3] === 'F') wide.push(range)
  else if (m[3] === 'A') ambiguous.push(range)
}

// Neighbouring ranges merge, so the lookup tables stay short.
function merge(ranges) {
  ranges.sort((a, b) => a[0] - b[0])
  const out = []
  for (const [a, b] of ranges) {
    const last = out.at(-1)
    if (last && a <= last[1] + 1) last[1] = Math.max(last[1], b)
    else out.push([a, b])
  }
  return out
}

function table(ranges) {
  const pairs = merge(ranges).map(([a, b]) => `0x${a.toString(16)}, 0x${b.toString(16)}`)
  const lines = []
  for (let i = 0; i < pairs.length; i += 6) lines.push('  ' + pairs.slice(i, i + 6).join(', ') + ',')
  return lines.join('\n')
}

console.log(`// Display width of text in a monospace grid, from Unicode ${version}
// EastAsianWidth.txt. Generated by reviews/ascii-art/gen-width-tables.mjs.
//
// Wide (W, F): 2 cells everywhere. CJK text and most emoji.
// Ambiguous (A): 1 cell in most terminals, 2 when a terminal is set to treat
// ambiguous width as wide (common for CJK users). Box lines, arrows, blocks.
// Zero width: combining marks, format characters, variation selectors.

const WIDE = [
${table(wide)}
]

const AMBIGUOUS = [
${table(ambiguous)}
]

const ZERO = /[\\p{Mn}\\p{Me}\\p{Cf}\\u{FE00}-\\u{FE0F}]/u

function inTable(t, cp) {
  let lo = 0
  let hi = t.length / 2 - 1
  while (lo <= hi) {
    const mid = (lo + hi) >> 1
    if (cp < t[mid * 2]) hi = mid - 1
    else if (cp > t[mid * 2 + 1]) lo = mid + 1
    else return true
  }
  return false
}

export const UNICODE_VERSION = '${version}'
export const isWide = (cp) => inTable(WIDE, cp)
export const isAmbiguous = (cp) => inTable(AMBIGUOUS, cp)
export const isZeroWidth = (ch) => ZERO.test(ch)

// Cells one character takes. cjk: count ambiguous characters as 2.
export function charWidth(ch, cjk = false) {
  const cp = ch.codePointAt(0)
  if (isZeroWidth(ch)) return 0
  if (isWide(cp)) return 2
  if (cjk && isAmbiguous(cp)) return 2
  return 1
}

export function strWidth(s, cjk = false) {
  let w = 0
  for (const ch of s) w += charWidth(ch, cjk)
  return w
}

// Pads to a display width, so CJK text lines up in tables.
export function padEnd(s, width, cjk = false) {
  return s + ' '.repeat(Math.max(0, width - strWidth(s, cjk)))
}

export function padStart(s, width, cjk = false) {
  return ' '.repeat(Math.max(0, width - strWidth(s, cjk))) + s
}`)
